-- PostgreSQL dialect. All objects are isolated in the section_a schema.
-- Sample rows are synthetic fixtures, not official transaction or IPL data.

CREATE SCHEMA IF NOT EXISTS section_a;

CREATE TABLE IF NOT EXISTS section_a.reciprocal_transfers (
    transaction_id        BIGINT PRIMARY KEY,
    sender_account        TEXT NOT NULL CHECK (BTRIM(sender_account) <> ''),
    receiver_account      TEXT NOT NULL CHECK (BTRIM(receiver_account) <> ''),
    amount                NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
    transaction_timestamp TIMESTAMPTZ NOT NULL,
    CHECK (sender_account <> receiver_account)
);

CREATE INDEX IF NOT EXISTS reciprocal_transfers_accounts_time_idx
    ON section_a.reciprocal_transfers
       (sender_account, receiver_account, transaction_timestamp);

CREATE TABLE IF NOT EXISTS section_a.ipl_players (
    player_id   INTEGER PRIMARY KEY,
    player_name TEXT NOT NULL CHECK (BTRIM(player_name) <> '')
);

CREATE TABLE IF NOT EXISTS section_a.ipl_matches (
    match_id    INTEGER PRIMARY KEY,
    season_year SMALLINT NOT NULL CHECK (season_year = 2024),
    match_number SMALLINT NOT NULL CHECK (match_number > 0),
    match_date  DATE NOT NULL,
    home_team   TEXT NOT NULL,
    away_team   TEXT NOT NULL,
    UNIQUE (season_year, match_number),
    CHECK (home_team <> away_team)
);

-- One row per player's innings score. The schema allows multiple innings for
-- one player/match so the query can aggregate them before applying the 30-run
-- threshold. The sample includes one deliberately synthetic split-innings
-- fixture to exercise that aggregation path.
CREATE TABLE IF NOT EXISTS section_a.ipl_player_innings (
    innings_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id       INTEGER NOT NULL REFERENCES section_a.ipl_matches (match_id),
    player_id      INTEGER NOT NULL REFERENCES section_a.ipl_players (player_id),
    innings_number SMALLINT NOT NULL CHECK (innings_number BETWEEN 1 AND 4),
    runs_scored    SMALLINT NOT NULL CHECK (runs_scored BETWEEN 0 AND 300),
    UNIQUE (match_id, player_id, innings_number)
);

CREATE INDEX IF NOT EXISTS ipl_player_innings_match_player_idx
    ON section_a.ipl_player_innings (match_id, player_id);

